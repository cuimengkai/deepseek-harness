export type AgentModeSettingsKey = keyof typeof en

/** Locale key pair for a known shipped mode. */
interface ModeLocaleKeys {
  name: AgentModeSettingsKey
  description: AgentModeSettingsKey
}

const BUILT_IN_MODE_KEYS: Readonly<Partial<Record<string, ModeLocaleKeys>>> = {
  'hello-orchestration': {
    name: 'mode.helloOrchestrationName',
    description: 'mode.helloOrchestrationDescription',
  },
}

/** Source fields for mode display text. */
export interface ModeDisplaySource {
  readonly id: string
  readonly trust: 'system' | 'user'
  readonly name?: string
  readonly description?: string
}

/**
 * Resolve mode display copy: localized for known shipped samples, else file metadata.
 * @param mode - roster row.
 * @param t - locale lookup.
 * @returns display name and optional description.
 */
export function modeDisplayText(
  mode: ModeDisplaySource,
  t: (key: AgentModeSettingsKey) => string,
): { name: string; description?: string } {
  const keys = mode.trust === 'system' ? BUILT_IN_MODE_KEYS[mode.id] : undefined
  if (keys !== undefined) {
    return { name: t(keys.name), description: t(keys.description) }
  }
  return {
    name: mode.name ?? mode.id,
    ...mode.description === undefined ? {} : { description: mode.description },
  }
}
